function candidate(
  id: string,
  name: string,
  email: string,
  phone: string,
  profile: Partial<Candidate["profile"]> & { fullName?: string },
  incomplete = false,
): Candidate {
  const skills = profile.skills ?? (incomplete ? [] : ["Site safety"]);
  const p = {
    fullName: profile.fullName ?? name,
    phone: profile.phone ?? phone,
    city: profile.city ?? (incomplete ? "" : "Dhaka"),
    skills,
    experience: profile.experience ?? (incomplete ? "" : "3 years relevant trade experience (demo)."),
    education: profile.education ?? (incomplete ? "" : "SSC / trade training (demo)."),
    languages: profile.languages ?? (incomplete ? [] : ["Bengali", "English"]),
    preferredCategories: profile.preferredCategories ?? (incomplete ? [] : ["construction"]),
    preferredDestinations: profile.preferredDestinations ?? (incomplete ? [] : ["UAE"]),
    dateOfBirth: profile.dateOfBirth,
    completionPercent: 0,
  };
  const checks = [
    p.fullName,
    p.phone,
    p.city,
    p.skills.length,
    p.experience,
    p.education,
    p.languages.length,
    p.preferredCategories.length,
    p.preferredDestinations.length,
  ].filter(Boolean).length;
  p.completionPercent = Math.round((checks / 9) * 100);
  return {
    id,
    name,
    email,
    phone,
    profile: p,
    notes: incomplete ? "Incomplete demo profile." : "Demo candidate.",
    createdAt: "2026-06-01T08:00:00.000Z",
    isDemo: true,
  };
}

